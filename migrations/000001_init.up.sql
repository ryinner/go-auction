CREATE TYPE lot_status AS ENUM ('active', 'finished');
CREATE TABLE users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(255) NOT NULL UNIQUE CHECK (email = lower(email)),
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE lots (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(255) NOT NULL CHECK (title <> ''),
  start_price INTEGER NOT NULL CHECK (start_price > 0),
  current_price INTEGER NOT NULL,
  step INTEGER NOT NULL CHECK (step > 0),
  ends_at TIMESTAMPTZ NOT NULL,
  status lot_status NOT NULL DEFAULT 'active',
  owner_id INTEGER NOT NULL REFERENCES users (id),
  leader_id INTEGER REFERENCES users (id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT lots_current_price_check CHECK (current_price >= start_price),
  CONSTRAINT lots_ends_at_check CHECK (ends_at > created_at)
);
CREATE TABLE bids (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lot_id INTEGER NOT NULL REFERENCES lots (id),
  bidder_id INTEGER NOT NULL REFERENCES users (id),
  amount INTEGER NOT NULL CHECK (amount > 0),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX lots_status_ends_at_idx ON lots (status, ends_at);
CREATE INDEX bids_lot_id_id_idx ON bids (lot_id, id DESC);
CREATE INDEX lots_owner_id_idx ON lots (owner_id);
CREATE INDEX bids_bidder_id_idx ON bids (bidder_id);